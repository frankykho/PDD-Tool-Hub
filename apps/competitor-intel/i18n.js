const combos = (pairs) => {
  const out = {};
  for (let m = 1; m < 1 << pairs.length; m++) {
    const a = pairs.filter((_, i) => m & (1 << i));
    out[a.map((x) => x[0]).join(", ")] = a.map((x) => x[1]).join(", ");
  }
  return out;
};
