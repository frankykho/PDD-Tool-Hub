// pola umum: "Label (3)", "Label (opsional)" -> bagian di luar & di dalam kurung diterjemahkan masing-masing
const GENERIC = { "{x} ({n})": "{x} ({n})" };
// pesan tampil apa adanya ("... diisi.") atau diawali ✗ (titik dibuang mesin): dua-duanya dimasukkan, supaya kunci dengan titik
// cocok persis lebih dulu dan tidak tertangkap pola pendek seperti "Tanggal {t}"
const withDot = (o) => Object.fromEntries(Object.entries(o).flatMap(([k, v]) => [[k + ".", v + "."], [k, v]]));
// pola dicoba berurutan: yang teks tetapnya paling panjang (paling khusus) lebih dulu
const lit = (k) => (k in GENERIC ? -1 : k.includes("{") ? k.replace(/\{\w+\}/g, "").length : 1e6);
export default Object.fromEntries(Object.entries({ ...D, ...withDot(ERR), ...GENERIC }).sort(([a], [b]) => lit(b) - lit(a)));
